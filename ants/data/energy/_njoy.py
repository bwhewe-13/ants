def create_sand_ii_groups(ign):
    """Create SAND-II 620 (IGN 12) and 640 (IGN 15) -group energy structure."""

    deltl = np.array([5.0e0, 7.5e0, 10.0e0, 15.0e0, 20.0e0, 25.0e0, 30.0e0, 40.0e0])
    ndelta = np.array([2, 6, 10, 19, 23, 28, 36, 40, 46])

    if ign == 12:
        ngn = 620
    elif ign == 15:
        ngn = 640
    else:
        raise ValueError(f"Invalid ign={ign}. Must be 12 or 15.")

    ngp = ngn + 1
    ebounds = np.zeros((ngp,))

    ebounds[0] = _SANDA  # 0.1 meV

    for ig in range(8):
        delta = deltl[ig] * _SANDB
        n1 = ndelta[ig] - 1
        n2 = ndelta[ig + 1] - 1

        for n in range(n1, n2):
            ebounds[n] = ebounds[n - 1] + delta

    ebounds[20] = _SANDC

    for ig in range(45, 450):
        ebounds[ig] = ebounds[ig - 45] * 10

    ebounds[450] = _SANDD  # 1 MeV

    for ig in range(451, ngp):
        ebounds[ig] = ebounds[ig - 1] + _SANDE

    return ebounds


BOUNDS_NJOY_IGN12 = create_sand_ii_groups(12)


