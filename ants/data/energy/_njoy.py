def create_gam_ii_groups():
    """Create GAM-II 100-group energy structure (IGN 7)."""
    ngn = 100
    ngp = 101
    ebounds = np.zeros((ngp,))

    u = -4 * _TENTH
    du = _TENTH

    for ig in range(1, ngn):
        u = u + du
        ebounds[100 - ig] = u
        if ig == 49:
            du = _QUART

    # Manual boundary assignments
    ebounds[0] = _BGAM2
    ebounds[-1] = _TGAM2

    ebounds = convert_lethargy_to_energies(ebounds)

    return ebounds


